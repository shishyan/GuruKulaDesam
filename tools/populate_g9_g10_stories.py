def update_grades_9_and_10():
    for g, stories in [(9, G9_STORIES), (10, G10_STORIES)]:
        fname = f"data/books/grade_{g}.json"
        with open(fname, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        updated = 0
        for bk_name in ["nanneri", "nallaram", "nalvazhi"]:
            if bk_name in data["books"]:
                for ch in data["books"][bk_name]["chapters"]:
                    cnum = ch["chapterNumber"]
                    key = (bk_name, cnum)
                    if key in stories:
                        ch["story"] = stories[key]
                        updated += 1
        
        with open(fname, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        
        print(f"Grade {g} updated successfully! {updated} stories populated.")

if __name__ == "__main__":
    update_grades_9_and_10()
