def strip_decorative_unicode(text: str) -> str:
    """Remove all emojis, pictographs, dingbats, and decorative symbols while preserving Tamil and clean ASCII punctuation."""
    cleaned = []
    for ch in text:
        cp = ord(ch)
        if ch in ("\n", "\t") or (0x20 <= cp <= 0x7E) or (0x0B80 <= cp <= 0x0BFF):
            cleaned.append(ch)
        elif cp in (0x2013, 0x2014):
            cleaned.append("-")
        elif cp in (0x2018, 0x2019, 0x201C, 0x201D):
            cleaned.append("'")
    return "".join(cleaned)


def _fmt_ta_period(dt: datetime) -> str:
    """Format an IST datetime cleanly in Tamil without English AM/PM clutter."""
    h = dt.hour
    m = dt.minute
    if 0 <= h < 4:
        period = "அதிகாலை"
    elif 4 <= h < 6:
        period = "வைகறை"
    elif 6 <= h < 12:
        period = "காலை"
    elif 12 <= h < 16:
        period = "மதியம்"
    elif 16 <= h < 19:
        period = "மாலை"
    else:
        period = "இரவு"
    h12 = h % 12
    if h12 == 0:
        h12 = 12
    return f"{period} {h12:02d}:{m:02d}"


def _fmt_ta_span(start_dt: datetime, end_dt: datetime, ref_date: date) -> str:
    """Format exact IST start-end transition span in dignified Tamil."""
    def _part(dt: datetime) -> str:
        clock_ta = _fmt_ta_period(dt)
        if dt.date() == ref_date:
            return clock_ta
        return f"{GREGORIAN_MONTHS_TA[dt.month]} {dt.day:02d} {clock_ta}"

    return f"{_part(start_dt)} முதல் {_part(end_dt)} வரை"


def _fmt_fixed_slot_ta(slot_str: str) -> str:
    """Convert '07:45 AM – 08:45 AM' into clean Tamil 'காலை 07:45 - 08:45'."""
    parts = [p.strip() for p in slot_str.replace("–", "-").split("-")]
    if len(parts) != 2:
        return slot_str

    def _parse_ampm(s: str) -> tuple[int, int]:
        toks = s.split()
        hh, mm = [int(x) for x in toks[0].split(":")]
        ap = toks[1].upper() if len(toks) > 1 else "AM"
        if ap == "PM" and hh != 12:
            hh += 12
        elif ap == "AM" and hh == 12:
            hh = 0
        return hh, mm

    h1, m1 = _parse_ampm(parts[0])
    h2, m2 = _parse_ampm(parts[1])
    dt1 = datetime(2026, 1, 1, h1, m1, tzinfo=IST)
    p1 = _fmt_ta_period(dt1)
    h2_12 = h2 % 12 or 12
    return f"{p1} - {h2_12:02d}:{m2:02d}"


def get_tamil_solar_date(d: date) -> tuple[int, str, str, int]:
    """
    Authentic Tamil Aparahna/Sunset Sankranti Rule:
    If Sun enters a new sidereal sign before sunset (~18:00 IST), that civil day is Day 1 of the new Tamil month;
    if Sankranti occurs after sunset, the following civil day is Day 1.
    Guarantees exact Nov-Dec 2026 transitions with zero off-by-one jumps:
      - 2026-11-08 = ஐப்பசி 22 .. 2026-11-16 = ஐப்பசி 30
      - 2026-11-17 = கார்த்திகை 1 .. 2026-12-15 = கார்த்திகை 29
      - 2026-12-16 = மார்கழி 1 .. 2026-12-31 = மார்கழி 16
    """
    dt_sunset = datetime(d.year, d.month, d.day, 18, 0, 0, tzinfo=IST)
    m_idx = _solar_lunar_positions(dt_sunset)["month_idx"]
    day1 = d
    for back in range(1, 35):
        prev_d = d - timedelta(days=back)
        prev_sunset = datetime(prev_d.year, prev_d.month, prev_d.day, 18, 0, 0, tzinfo=IST)
        if _solar_lunar_positions(prev_sunset)["month_idx"] == m_idx:
            day1 = prev_d
        else:
            break
    tamil_day = (d - day1).days + 1
    m_ta, m_en = TAMIL_MONTHS[m_idx]
    return m_idx, m_ta, m_en, tamil_day


