def _build_single_rasi_prediction(rasi_idx: int, ctx: dict[str, Any]) -> str:
    """
    Deterministically compute an astrological prediction for `rasi_idx` (0..11) from:
      - Exact Moon house transit: `house = ((chandra_rasi_idx - rasi_idx) % 12) + 1` (1..12)
      - Weekday lord (`ஞாயிறு..சனி`) & Nakshatra lord (`கேது..புதன்`)
    """
    chandra_idx = ctx["chandra_rasi_idx"]
    house = ((chandra_idx - rasi_idx) % 12) + 1
    base_text, worship_tag = HOUSE_PREDICTIONS_TA[house]

    wd_lord = ctx["wd_ext"]["lord_ta"]
    nak_lord = ctx["nak_lord_ta"]
    color_idx = (rasi_idx + ctx["wd"] * 2 + ctx["n_idx"]) % len(LUCKY_COLORS_BY_RASI_HOUSE)
    lucky_color = LUCKY_COLORS_BY_RASI_HOUSE[color_idx]

    if house == 8:
        # Explicit Chandrashtamam wording required
        return (
            f"{base_text} | சுப நிறம்: {lucky_color} | வழிபாடு: {worship_tag}."
        )

    flavor = LORD_FLAVOR_TA.get(nak_lord if (rasi_idx + ctx["wd"]) % 2 == 0 else wd_lord, "நம்பிக்கையுடன்")
    return (
        f"{flavor} செயல்படும் நாள்; {base_text} | அதிர்ஷ்ட நிறம்: {lucky_color} | வழிபாடு: {worship_tag}."
    )


def build_cat2_raasi_jothidam_post(date_str: str) -> str:
    """
    Build Category 2 Tamil Community Post (`இன்றைய ராசி பலன்கள் & மகளிர் ஜோதிட வழிகாட்டி`) for `@TamilDailyLife`.
    Includes all 12 Rasis from astronomical Moon house transit + 1 unique daily Home Vastu/Jyotisha tip (0..53).
    Zero emojis/pictographs, < 3,800 Unicode chars.
    """
    ctx = get_daily_astro_context(date_str)
    wd_ext = ctx["wd_ext"]
    day_idx = ctx["day_offset"]
    if not (0 <= day_idx < len(FIFTY_FOUR_VASTU_JYOTISHA_TIPS_TA)):
        day_idx = day_idx % len(FIFTY_FOUR_VASTU_JYOTISHA_TIPS_TA)
    vastu_tip = FIFTY_FOUR_VASTU_JYOTISHA_TIPS_TA[day_idx]

    lines = [
        f"இன்றைய ராசி பலன்கள் & மகளிர் ஜோதிட வழிகாட்டி | {ctx['greg_date_ta']} ({ctx['m_ta']} {ctx['tamil_day']}, {ctx['wd_ta']})",
        "",
        (
            f"இன்றைய சந்திர சஞ்சாரம்: {ctx['chandra_rasi_ta']} ராசி - {ctx['nak_ta']} நட்சத்திரம் "
            f"(நட்சத்திர அதிபதி: {ctx['nak_lord_ta']}) | இன்றைய சுப நிறங்கள்: {wd_ext['auspicious_colors']}."
        ),
        "",
        "பன்னிரு ராசி பலன்கள் (மகளிர் & குடும்பச் சிறப்புப் பலன்கள்):",
    ]

    for r_idx, r_name in enumerate(RASI_NAMES_TA):
        pred = _build_single_rasi_prediction(r_idx, ctx)
        lines.append(f"- {r_name}: {pred}")

    lines.extend([
        "",
        "மகளிர் ஜோதிட & வாஸ்து குறிப்பு:",
        f"- {vastu_tip}",
        "",
        f"{wd_ext['weekday_tone_ta']}; நவக்கிரகங்களின் நல்லருளால் உங்கள் குடும்பத்தில் மகிழ்ச்சியும் ஆரோக்கியமும் தழைக்கட்டும்.",
        "வாழ்க வளமுடன். சிவாயநம.",
        "",
        "#TamilDailyLife #TamilVirtues #ராசிபலன் #இன்றையராசிபலன் #தமிழ்ஜோதிடம் #வாஸ்து #மகளிர்ஜோதிடம் #RasiPalan #TamilAstrology #GuruKulaDesam",
    ])

    post = strip_decorative_unicode("\n".join(lines)).strip()
    assert len(post) < 3800, f"Cat 2 post exceeded 3800 chars ({len(post)}) on {date_str}"
    return post


def verify_all_54_days(verbose_samples: tuple[str, ...] = ("2026-11-08", "2026-11-22", "2026-12-16")) -> dict[str, Any]:
    """Run deterministic & astronomical verification across all 54 dates from 2026-11-08 through 2026-12-31."""
    assert len(FIFTY_FOUR_VASTU_JYOTISHA_TIPS_TA) == 54, "Must have exactly 54 Vastu/Jyotisha tips"
    assert len(set(FIFTY_FOUR_VASTU_JYOTISHA_TIPS_TA)) == 54, "All 54 Vastu/Jyotisha tips must be 100% unique"

    max_cat1 = 0
    max_cat2 = 0
    prev_m_idx = None
    prev_t_day = None
    records = []

    for offset in range(54):
        d = START_DATE + timedelta(days=offset)
        d_str = d.isoformat()
        ctx = get_daily_astro_context(d_str)
        story_meta = load_story_meta(d_str)

        # Verify Tamil month & day transitions
        if d_str == "2026-11-08":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("ஐப்பசி", 22), f"Expected ஐப்பசி 22, got {ctx['m_ta']} {ctx['tamil_day']}"
        elif d_str == "2026-11-16":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("ஐப்பசி", 30), f"Expected ஐப்பசி 30, got {ctx['m_ta']} {ctx['tamil_day']}"
        elif d_str == "2026-11-17":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("கார்த்திகை", 1), f"Expected கார்த்திகை 1, got {ctx['m_ta']} {ctx['tamil_day']}"
        elif d_str == "2026-12-15":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("கார்த்திகை", 29), f"Expected கார்த்திகை 29, got {ctx['m_ta']} {ctx['tamil_day']}"
        elif d_str == "2026-12-16":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("மார்கழி", 1), f"Expected மார்கழி 1, got {ctx['m_ta']} {ctx['tamil_day']}"
        elif d_str == "2026-12-31":
            assert (ctx["m_ta"], ctx["tamil_day"]) == ("மார்கழி", 16), f"Expected மார்கழி 16, got {ctx['m_ta']} {ctx['tamil_day']}"

        if prev_m_idx is not None:
            if ctx["m_idx"] == prev_m_idx:
                assert ctx["tamil_day"] == prev_t_day + 1, f"Tamil day jump on {d_str}: {prev_t_day} -> {ctx['tamil_day']}"
            else:
                assert ctx["tamil_day"] == 1, f"New Tamil month must start on day 1 on {d_str}, got {ctx['tamil_day']}"
        prev_m_idx = ctx["m_idx"]
        prev_t_day = ctx["tamil_day"]

        # Verify 8th-house Chandrashtamam math
        assert ((ctx["chandra_rasi_idx"] - ctx["chandrashtama_rasi_idx"]) % 12) == 7

        cat1 = build_cat1_panchangam_post(d_str, story_meta)
        cat2 = build_cat2_raasi_jothidam_post(d_str)

        assert cat1 == strip_decorative_unicode(cat1)
        assert cat2 == strip_decorative_unicode(cat2)
        assert f"- {ctx['chandrashtama_rasi_ta']}: இன்று சந்திராஷ்டமம் என்பதால்" in cat2

        max_cat1 = max(max_cat1, len(cat1))
        max_cat2 = max(max_cat2, len(cat2))
        records.append((d_str, ctx, cat1, cat2))

    for sample_date in verbose_samples:
        for d_str, _, cat1, cat2 in records:
            if d_str == sample_date:
                print("=" * 92)
                print(f"SAMPLE DATE: {d_str} | CATEGORY 1 ({len(cat1)} chars)")
                print("=" * 92)
                print(cat1)
                print("-" * 92)
                print(f"SAMPLE DATE: {d_str} | CATEGORY 2 ({len(cat2)} chars)")
                print("-" * 92)
                print(cat2)
                print()

    summary = {
        "total_days": len(records),
        "start_date": START_DATE.isoformat(),
        "end_date": END_DATE.isoformat(),
        "max_cat1_chars": max_cat1,
        "max_cat2_chars": max_cat2,
    }
    print("=" * 92)
    print(f"VERIFICATION PASSED: {summary}")
    print("=" * 92)
    return summary


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)

    parser = argparse.ArgumentParser(description="Build @TamilDailyLife Cat 1 & Cat 2 Astrological Community Posts")
    parser.add_argument("--date", default="", help="Single YYYY-MM-DD date to print (default: run 54-day verification)")
    parser.add_argument("--category", type=int, choices=[0, 1, 2], default=0, help="1=Panchangam, 2=Rasi Palan, 0=Both")
    args = parser.parse_args()

    if args.date:
        if args.category in (0, 1):
            print(build_cat1_panchangam_post(args.date))
        if args.category == 0:
            print("\n" + ("-" * 80) + "\n")
        if args.category in (0, 2):
            print(build_cat2_raasi_jothidam_post(args.date))
    else:
        verify_all_54_days()


if __name__ == "__main__":
    main()
