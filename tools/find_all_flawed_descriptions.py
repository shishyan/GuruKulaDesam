for v in videos:
    vid = v['id']
    snip = v.get('snippet', {})
    title = snip.get('title', '')
    desc = snip.get('description', '')
    
    # Exclude DistroKid auto-generated art tracks unless prompt leakage
    is_art_track = "provided to youtube by distrokid" in desc.lower() or "auto-generated by youtube" in desc.lower()
    
    # 1. Prompt Leakage
    if any(p in title.lower() for p in ['create album', 'generate ', 'prompt:']) or any(p in desc.lower() for p in ['create album', 'prompt:']):
        results["corrupted_or_prompt_leakage"].append({
            "id": vid,
            "title": title,
            "desc_len": len(desc),
            "issue": "Raw AI generation prompt found in title or description"
        })
        
    if is_art_track:
        continue

    # 2. Check for No Lyrics At All
    has_lyrics_tag = any(t in desc for t in ["பாடல் வரிகள்", "LYRICS", "Lyrics", "பாடல்:", "வரிகள்:"])
    
    # Check if description is trivial / empty or has no lyrics text
    desc_cleaned = re.sub(r'https?://\S+', '', desc)
    desc_cleaned = re.sub(r'#\S+', '', desc_cleaned)
    desc_cleaned = re.sub(r'═+', '', desc_cleaned).strip()
    
    if len(desc) < 250 or not has_lyrics_tag:
        # Check if it has actual devotional lyrics inside
        has_any_tamil_lines = False
        tamil_verses = [line.strip() for line in desc.split('\n') if re.search(r'[\u0B80-\u0BFF]{15,}', line)]
        if len(tamil_verses) < 2:
            results["no_lyrics_at_all"].append({
                "id": vid,
                "title": title,
                "desc_len": len(desc),
                "issue": f"No lyrics section in description (Desc length: {len(desc)} characters)"
            })
            continue

    # 3. Check for specific works: Truncation or Mismatches
    title_lower = title.lower()
    for w_name, w_info in WORKS.items():
        if any(kw in title or kw in title_lower for kw in w_info['title_kw']):
            # Check Pancharatnam full verses
            if 'required_all_verses' in w_info:
                missing_v = [verse_kw for verse_kw in w_info['required_all_verses'] if verse_kw not in desc]
                if missing_v:
                    results["truncated_incomplete_lyrics"].append({
                        "id": vid,
                        "title": title,
                        "work": w_name,
                        "missing_verses_indicators": missing_v,
                        "issue": f"Ganesha Pancharatnam missing {len(missing_v)} verses ({missing_v})"
                    })
            # Check other works required verses
            elif 'required' in w_info:
                if not any(req in desc for req in w_info['required']):
                    # Check what lyrics are actually there
                    curr_lyrics_sample = ""
                    if "பாடல் வரிகள்" in desc:
                        curr_lyrics_sample = desc.split("பாடல் வரிகள்")[1][:100].replace('\n', ' ').strip()
                    results["mismatched_wrong_lyrics"].append({
                        "id": vid,
                        "title": title,
                        "work": w_name,
                        "expected": w_info['required'],
                        "found_sample": curr_lyrics_sample,
                        "issue": f"Title is {w_name}, but description lacks canonical verse {w_info['required']}"
                    })

print("="*70)
print(f"1. NO LYRICS AT ALL: {len(results['no_lyrics_at_all'])} videos")
print(f"2. WRONG / MISMATCHED LYRICS: {len(results['mismatched_wrong_lyrics'])} videos")
print(f"3. TRUNCATED / INCOMPLETE LYRICS: {len(results['truncated_incomplete_lyrics'])} videos")
print(f"4. CORRUPTED / PROMPT LEAKAGE: {len(results['corrupted_or_prompt_leakage'])} videos")
print("="*70)

with open('production/all_flawed_descriptions_audit.json', 'w', encoding='utf-8') as f:
    json.dump(results, f, indent=2, ensure_ascii=False)

print("Saved detailed report to production/all_flawed_descriptions_audit.json")
