for grade, spec in GRADE_SPECS.items():
    fpath = os.path.join(ROOT, f'tharam-{grade}.html')
    if not os.path.exists(fpath):
        continue
    with open(fpath, 'r', encoding='utf-8') as f:
        content = f.read()

    # 1. Update meta description
    content = re.sub(
        r'<meta name="description" content="[^"]*">',
        f'<meta name="description" content="{spec["meta_desc"]}">',
        content,
        count=1
    )

    # 2. Update grade-focus-bar text
    # Pattern: <div style="color:var\(--gold-soft\); font-size:0\.9rem; font-weight:700;">\s*📖[^<]*</div>
    content = re.sub(
        r'<div style="color:var\(--gold-soft\); font-size:0\.9rem; font-weight:700;">[\s\S]*?</div>',
        f'<div style="color:var(--gold-soft); font-size:0.9rem; font-weight:700;">\n          {spec["focus_bar"]}\n        </div>',
        content,
        count=1
    )

    # 3. Update shelf heading and subtitle
    # <h3 style="color:#ffffff; font-size:1.15rem; font-weight:800; margin:0;">...</h3>\s*<span style="color:#94a3b8; font-size:0.82rem;">...</span>
    content = re.sub(
        r'<h3 style="color:#ffffff; font-size:1\.15rem; font-weight:800; margin:0;">[^<]*</h3>\s*<span style="color:#94a3b8; font-size:0\.82rem;">[^<]*</span>',
        f'<h3 style="color:#ffffff; font-size:1.15rem; font-weight:800; margin:0;">{spec["shelf_h3"]}</h3>\n        <span style="color:#94a3b8; font-size:0.82rem;">{spec["shelf_sub"]}</span>',
        content,
        count=1
    )

    # 4. Update readerBookBadge default text
    content = re.sub(
        r'<span class="pat-level-code-pill" id="readerBookBadge">[^<]*</span>',
        f'<span class="pat-level-code-pill" id="readerBookBadge">{spec["stage_badge"]}</span>',
        content,
        count=1
    )

    with open(fpath, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"Updated headers & focus bar in tharam-{grade}.html")

print("All grade pages updated.")
