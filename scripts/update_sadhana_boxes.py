def update_grades():
    sadhana_regex = re.compile(r'<section id="sadhanaBox".*?</section>', re.DOTALL)
    for g in range(2, 13):
        fn = ROOT / f"tharam-{g}.html"
        if not fn.exists():
            continue
        content = fn.read_text(encoding='utf-8')
        new_sadhana = generate_sadhana_html(g)
        m = sadhana_regex.search(content)
        if m:
            updated_content = content[:m.start()] + new_sadhana + content[m.end():]
            fn.write_text(updated_content, encoding='utf-8')
            print(f"[REPLACED] {fn.name}")
        else:
            footer_idx = content.find('<footer class="site-footer">')
            if footer_idx != -1:
                updated_content = content[:footer_idx] + "  <!-- Dedicated Grade Sadhana & Domestic Dharma Practice Box -->\n" + new_sadhana + "\n\n  " + content[footer_idx:]
                fn.write_text(updated_content, encoding='utf-8')
                print(f"[INSERTED] {fn.name}")
            else:
                print(f"[NO FOOTER] {fn.name}")

if __name__ == '__main__':

    update_grades()

