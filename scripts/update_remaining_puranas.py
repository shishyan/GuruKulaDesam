def update_all_remaining():
    for filename, chapters in purana_stories.items():
        filepath = f"data/puranas/{filename}"
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        for i, text in enumerate(chapters):
            if i < len(data['chapters']):
                data['chapters'][i]['exposition'] = text
        
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Updated {filename} successfully ({len(chapters)} chapters)!")

update_all_remaining()
